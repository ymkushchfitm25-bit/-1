
#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Програма для демонстрації операцій зі списками цілих чисел.
Виконує операції індексування, зрізування та модифікації списків.
"""

def print_separator(title=""):
    """Виводить розділювач для читабельності."""
    if title:
        print(f"\n{'='*60}")
        print(f"  {title}")
        print(f"{'='*60}")
    else:
        print(f"{'-'*60}")

def print_list_state(lst, label="Поточний стан списку"):
    """Виводить список з індексами для наочності."""
    print(f"\n{label}:")
    print(f"  Вміст: {lst}")
    print(f"  Довжина: {len(lst)}")
    # Виведення індексів
    if lst:
        print(f"  Індекси (позитивні):  {list(range(len(lst)))}")
        print(f"  Індекси (негативні):  {list(range(-len(lst), 0))}")

def load_data_from_constant():
    """Завантажує дані з константи (детерміновано)."""
    print_separator("КРОК 1: Завантаження даних з константи")

    # Початковий список цілих чисел
    initial_list = [10, 20, 30, 40, 50, 60, 70, 80]

    print("Дані завантажені з константи у коді.")
    print_list_state(initial_list, "Початковий список")

    return initial_list

def demonstrate_indexing(lst):
    """Демонструє звернення за додатним і від'ємним індексом."""
    print_separator("КРОК 2: Звернення до елементів за індексом")

    print("\n--- Додатні індекси ---")
    print(f"  lst[0] = {lst[0]}  (перший елемент)")
    print(f"  lst[2] = {lst[2]}  (третій елемент)")
    print(f"  lst[5] = {lst[5]}  (шостий елемент)")

    print("\n--- Від'ємні індекси ---")
    print(f"  lst[-1] = {lst[-1]}  (останній елемент)")
    print(f"  lst[-3] = {lst[-3]}  (третій з кінця)")
    print(f"  lst[-7] = {lst[-7]}  (сьомий з кінця)")

    print("\nІнтерпретація: від'ємний індекс -i еквівалентний індексу len(lst) - i")
    print(f"  len(lst) = {len(lst)}")
    print(f"  lst[-1] еквівалентний lst[{len(lst)-1}] = {lst[len(lst)-1]}")

def demonstrate_slicing(lst):
    """Демонструє різні типи зрізів."""
    print_separator("КРОК 3: Демонстрація зрізів списку")

    # Зріз 1: базовий зріз з кроком 1 (за замовчуванням)
    print("\n--- Зріз 1: lst[1:6] (елементи від індекса 1 до 5, не включаючи 6) ---")
    slice1 = lst[1:6]
    print(f"  Результат: {slice1}")
    print(f"  Це новий список, створений зі скопійованих елементів")
    print(f"  Теж саме, що lst[1:6:1]")

    # Зріз 2: зріз з кроком 2 (кожний другий елемент)
    print("\n--- Зріз 2: lst[::2] (кожний другий елемент з початку до кінця) ---")
    slice2 = lst[::2]
    print(f"  Результат: {slice2}")
    print(f"  Крок = 2, тому беремо елементи на позиціях 0, 2, 4, 6")
    print(f"  Теж саме, що lst[0:len(lst):2]")

    # Зріз 3: зріс у зворотному порядку з кроком -1
    print("\n--- Зріз 3: lst[::-1] (список у зворотному порядку) ---")
    slice3 = lst[::-1]
    print(f"  Результат: {slice3}")
    print(f"  Крок = -1, елементи розбірають з кінця до початку")
    print(f"  Теж саме, що lst[len(lst)-1::-1]")

    print("\n*** Важливо: всі зрізи повертають НОВІ списки, не змінюючи оригінал ***")
    print_list_state(lst, "Оригінальний список (без змін)")

def demonstrate_in_place_operations(lst):
    """Демонструє операції модифікації списку на місці."""
    print_separator("КРОК 4: Операції модифікації списку на місці (in-place)")

    # Операція 1: append() - додавання в кінець
    print("\n--- Операція 1: append(90) ---")
    print("Метод append() додає елемент в кінець списку та змінює оригінальний об'єкт")
    lst.append(90)
    print_list_state(lst, "Після append(90)")
    print("*** Це модифікація на місце - оригінальний об'єкт змінено! ***")

    # Операція 2: insert() - вставка за індексом
    print("\n--- Операція 2: insert(2, 25) ---")
    print("Метод insert(index, value) вставляє елемент на задану позицію")
    lst.insert(2, 25)
    print_list_state(lst, "Після insert(2, 25)")
    print("*** Це також модифікація на місце ***")

    # Операція 3: remove() - видалення за значенням
    print("\n--- Операція 3: remove(40) ---")
    print("Метод remove() видаляє перший елемент з заданим значенням")
    lst.remove(40)
    print_list_state(lst, "Після remove(40)")

    # Операція 4: del - видалення за індексом
    print("\n--- Операція 4: del lst[0] ---")
    print("Оператор del видаляє елемент(и) за індексом")
    del lst[0]
    print_list_state(lst, "Після del lst[0]")

    # Операція 5: заміна діапазону
    print("\n--- Операція 5: lst[1:4] = [100, 200, 300] ---")
    print("Можна замінити діапазон елементів на нові значення")
    lst[1:4] = [100, 200, 300]
    print_list_state(lst, "Після lst[1:4] = [100, 200, 300]")
    print("*** Всі ці операції змінюють ОРИГІНАЛЬНИЙ список на місці ***")

def demonstrate_list_creation():
    """Демонструє створення нових списків на базі існуючого."""
    print_separator("КРОК 5: Створення нових списків (копіювання)")

    original = [1, 2, 3, 4, 5]
    print_list_state(original, "Оригінальний список")

    # Способи створення нових списків
    print("\n--- Спосіб 1: зріз lst[:] ---")
    copy1 = original[:]
    print(f"  copy1 = original[:] -> {copy1}")
    print(f"  Це НОВА копія списку")

    print("\n--- Спосіб 2: конструктор list(lst) ---")
    copy2 = list(original)
    print(f"  copy2 = list(original) -> {copy2}")
    print(f"  Це також НОВА копія списку")

    print("\n--- Демонстрація: змоднимо copy1, оригінал залишиться без змін ---")
    copy1.append(999)
    print_list_state(copy1, "copy1 після append(999)")
    print_list_state(original, "original (без змін)")
    print("Видно, що оригінальний список не змінився!")

def main():
    """Головна функція програми."""
    print("\n")
    print("╔" + "="*58 + "╗")
    print("║" + " "*58 + "║")
    print("║" + "  ДЕМОНСТРАЦІЯ ОПЕРАЦІЙ ЗІ СПИСКАМИ ЦІЛИХ ЧИСЕЛ".center(58) + "║")
    print("║" + " "*58 + "║")
    print("╚" + "="*58 + "╝")

    # Крок 1: Завантаження даних
    numbers_list = load_data_from_constant()

    # Крок 2: Індексування
    demonstrate_indexing(numbers_list)

    # Крок 3: Зрізи
    demonstrate_slicing(numbers_list)

    # Крок 4: In-place операції
    demonstrate_in_place_operations(numbers_list)

    # Крок 5: Створення нових списків
    demonstrate_list_creation()

    # Фінальний висновок
    print_separator("ВИСНОВОК")
    print("\n✓ Продемонстровані операції з додатними та від'ємними індексами")
    print("✓ Показані 3 різні типи зрізів (базовий, з кроком, зворотний)")
    print("✓ Виконано 5 операцій модифікації списку на місці")
    print("✓ Пояснено різницю між створенням нових списків та модифікацією на місці")
    print("\nПрограма завершена успішно!\n")

if __name__ == "__main__":
    main()
